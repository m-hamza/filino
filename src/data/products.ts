export const relatedTo = (slug: string, n = 3) => {
  const p = productBySlug(slug);
  if (!p) return [];
  return products.filter((x) => x.slug !== slug && x.category === p.category).concat(products.filter((x) => x.slug !== slug && x.category !== p.category)).slice(0, n);
};
